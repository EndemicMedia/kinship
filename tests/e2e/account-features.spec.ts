test('account workflows validate, cancel and complete locally', async ({ page }) => {
  await login(page)
  await navigate(page, 'profile')
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Change Password', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('button', { name: 'Continue', exact: true })).toBeDisabled()
  await dialog.getByLabel('Current password', { exact: true }).fill('password')
  await dialog.getByLabel('New password', { exact: true }).fill('new-password')
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('Workflow complete')
  await dialog.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: 'Privacy Settings', exact: true }).click()
  const discoverable = dialog.getByRole('switch', { name: 'Show my profile in Compass', exact: true })
  await discoverable.click()
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: 'Privacy Settings', exact: true }).click()
  await expect(discoverable).toHaveAttribute('aria-checked', 'true')
  await discoverable.click()
  await dialog.getByRole('button', { name: 'Save privacy preferences', exact: true }).click()
  await dialog.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: 'Privacy Settings', exact: true }).click()
  await expect(discoverable).toHaveAttribute('aria-checked', 'false')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: 'Delete Account', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Confirm request', exact: true })).toBeDisabled()
  await dialog.getByRole('textbox').fill('DELETE')
  await dialog.getByRole('button', { name: 'Confirm request', exact: true }).click()
  await dialog.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await navigate(page, 'profile')
  await expect(page.getByRole('heading', { name: 'Alex Rivera', exact: true })).toBeVisible()
})

test('search, notifications, theme and activity remain accessible', async ({ page }) => {
  await login(page)
  const search = page.getByRole('button', { name: /Search Kinship|Search\.\.\./ }).first()
  await search.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('dialog').getByRole('combobox').fill('Create New Crew')
  await page.getByRole('option', { name: /Create New Crew/ }).click()
  await expect(page).toHaveURL(/\/kinship\/app\/crews\/create$/)
  await page.getByRole('button', { name: /^Notifications, / }).click()
  await page.getByRole('menuitem', { name: /New Match Found/ }).click()
  await expect(page).toHaveURL(/\/kinship\/app\/compass$/)
  await expect(page.getByRole('button', { name: 'Notifications, 1 unread', exact: true })).toBeVisible()
  const dark = await page.locator('html').evaluate(element => element.classList.contains('dark'))
  await page.getByRole('button', { name: 'Toggle color theme', exact: true }).click()
  await expect.poll(() => page.locator('html').evaluate(element => element.classList.contains('dark'))).toBe(!dark)
  await page.locator('a[href$="/app"]:visible').first().click()
  await page.getByRole('link', { name: 'View All', exact: true }).and(page.locator('a[href$="/app/activity"]')).click()
  await expect(page.getByRole('heading', { name: 'Recent Activity', exact: true })).toBeVisible()
  await page.getByRole('link', { name: /Created Document/ }).click()
  await expect(page).toHaveURL(/\/kinship\/app\/legal$/)
})

