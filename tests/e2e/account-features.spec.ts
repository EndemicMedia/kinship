import { test, expect, login, navigate, open } from './fixtures'

test('profile edits, cancellation, persona isolation and refresh work', async ({ page }) => {
  await login(page)
  await navigate(page, 'profile')
  await page.getByRole('button', { name: /Jordan & Sam Chen/ }).click()
  await expect(page.getByRole('heading', { name: 'Jordan & Sam Chen', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit Profile', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('Name', { exact: true })).toHaveValue('Jordan & Sam Chen')
  await dialog.getByLabel('Name', { exact: true }).fill('Unsaved name')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: 'Edit Profile', exact: true }).click()
  await expect(dialog.getByLabel('Name', { exact: true })).toHaveValue('Jordan & Sam Chen')
  await dialog.getByLabel('Bio', { exact: true }).fill('Shared intentions, saved independently.')
  await dialog.getByRole('button', { name: 'Save Changes', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await navigate(page, 'compass')
  await navigate(page, 'profile')
  await expect(page.getByText('Shared intentions, saved independently.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Jordan & Sam Chen', exact: true })).toBeVisible()
  await expect(page.getByText('Shared intentions, saved independently.', { exact: true })).toBeVisible()
  const alex = page.getByRole('button', { name: /Alex Rivera/ })
  await alex.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Alex Rivera', exact: true })).toBeVisible()
  await expect(page.getByText('Shared intentions, saved independently.', { exact: true })).toHaveCount(0)
})

test('Compass votes and filters have observable outcomes', async ({ page }) => {
  await login(page)
  await navigate(page, 'compass')
  const cards = page.getByTestId('match-card')
  const count = await cards.count()
  expect(count).toBeGreaterThan(2)
  const first = cards.first()
  await first.getByRole('button', { name: /^Like / }).click()
  await expect(page.getByTestId('liked-count')).toHaveText('1')
  await first.getByRole('button', { name: /^Maybe / }).click()
  await expect(page.getByTestId('maybe-count')).toHaveText('1')
  await expect(page.getByTestId('liked-count')).toHaveText('0')
  await first.getByRole('button', { name: /^Pass on / }).click()
  await expect(page.getByTestId('passed-count')).toHaveText('1')
  await page.getByRole('button', { name: 'Reset All Votes', exact: true }).click()
  await expect(page.getByTestId('passed-count')).toHaveText('0')
  await page.getByRole('button', { name: 'Filters', exact: true }).click()
  await page.locator('#compass-role').selectOption('genetic-provider')
  expect(await cards.count()).toBeLessThan(count)
  await page.getByRole('button', { name: 'Reset filters', exact: true }).click()
  await expect(cards).toHaveCount(count)
})

test('Compass profile actions save messages and prevent duplicate requests', async ({ page }) => {
  await login(page)
  await navigate(page, 'compass')
  const first = page.getByTestId('match-card').first()
  await first.getByRole('button', { name: 'Profile', exact: true }).click()
  await expect(page.getByRole('dialog').getByText('Compatibility Breakdown', { exact: true })).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: 'Message', exact: true }).click()
  await page.getByRole('dialog').getByPlaceholder('Type your message here...').fill('Let us discuss shared care.')
  await page.getByRole('dialog').getByRole('button', { name: 'Send Message', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await first.getByRole('button', { name: 'Message', exact: true }).click()
  await expect(page.getByRole('dialog').getByText('Let us discuss shared care.', { exact: true })).toHaveCount(1)
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await first.getByRole('button', { name: 'Profile', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Connect', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Send Request', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(first.getByRole('button', { name: 'Request pending', exact: true })).toBeDisabled()
  await navigate(page, 'profile')
  await navigate(page, 'compass')
  await expect(first.getByRole('button', { name: 'Request pending', exact: true })).toBeDisabled()
})

