import { test, expect, login, navigate, open } from './fixtures'

test('landing exposes its main content and app entry', async ({ page }) => {
  await open(page, './')
  await expect(page.getByRole('main')).toHaveCount(1)
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  await expect(page.getByRole('contentinfo')).toBeVisible()
  const openApp = page.getByRole('link', { name: 'Open App', exact: true }).first()
  await openApp.click()
  await expect(page).toHaveURL(/\/kinship\/app\/login$/)
  await expect(page.getByRole('heading', { name: 'Welcome to Kinship' })).toBeVisible()
})

test('login exposes inputs and rejects invalid credentials', async ({ page }) => {
  await open(page, './app/login')
  await page.locator('input[type="email"]').fill('nobody@example.com')
  await page.locator('input[type="password"]').fill('incorrect')
  await page.getByRole('button', { name: 'Sign In', exact: true }).click()
  await expect(page.getByText('Invalid email or password')).toBeVisible()
  await expect(page).toHaveURL(/\/app\/login$/)
  await expect(page.getByRole('button', { name: 'Sign In', exact: true })).toBeEnabled()
})

test('demo login, navigation, crew tabs and logout work', async ({ page }) => {
  await login(page)
  await expect(page.getByRole('heading', { name: 'Your Crews', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Messages Check messages', exact: true }).click()
  await expect(page.getByRole('tab', { name: 'Chat', exact: true })).toHaveAttribute('aria-selected', 'true')
  await navigate(page, 'compass')
  await expect(page.getByRole('heading', { name: 'The Compass', exact: true })).toBeVisible()
  await navigate(page, 'crews')
  await page.locator('a[href*="/app/crews/detail"]').first().click()
  await expect(page.getByRole('heading', { name: 'About', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Chat', exact: true }).click()
  await expect(page.locator('input[placeholder*="message"], textarea[placeholder*="message"]')).toBeVisible()
  await page.getByRole('tab', { name: 'Documents', exact: true }).click()
  await expect(page.getByRole('button', { name: /Create Document/ }).or(page.getByRole('link', { name: /Create Document/ }))).toBeVisible()
  await page.getByRole('tab', { name: 'Accountability', exact: true }).click()
  await expect(page.getByRole('button', { name: /Log Incident/ })).toBeVisible()
  await navigate(page, 'legal')
  await page.getByRole('tab', { name: 'Templates', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Use Template', exact: true }).first()).toBeVisible()
  await navigate(page, 'profile')
  await page.getByRole('button', { name: 'Log Out', exact: true }).click()
  await expect(page).toHaveURL(/\/app\/login$/)
})

test('saved persona restores on direct navigation and refresh', async ({ page }) => {
  await login(page)
  await open(page, './app/profile')
  await expect(page.getByRole('heading', { name: 'Profile', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Profile', exact: true })).toBeVisible()
  await open(page, './app/settings')
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
})

