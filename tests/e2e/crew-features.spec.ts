test('template drafts create, edit, reopen, sign and download in Legal and crew documents', async ({ page }) => {
  await login(page)
  await createCrew(page, 'Agreement Crew')
  await page.getByRole('tab', { name: 'Documents', exact: true }).click()
  await page.getByRole('link', { name: 'Create Document', exact: true }).click()
  await expect(page).toHaveURL(/\/app\/legal\?crewId=/)
  const crewId = new URL(page.url()).searchParams.get('crewId')
  await page.getByRole('tab', { name: 'Templates', exact: true }).click()
  await page.getByRole('button', { name: 'Preview', exact: true }).first().click()
  await page.getByRole('dialog').getByRole('button', { name: 'Use This Template', exact: true }).click()
  const modal = page.getByRole('dialog')
  await expect(modal.getByRole('textbox', { name: 'Document Title', exact: true })).toHaveValue('Co-Parenting Agreement Template')
  await expect(modal.getByRole('textbox', { name: 'Document content', exact: true })).toHaveValue(/Parenting Time Schedule/)
  await expect(modal.getByRole('combobox', { name: 'Crew', exact: true })).toHaveValue(crewId!)
  await modal.getByRole('textbox', { name: 'Document Title', exact: true }).fill('Our agreement')
  await modal.getByRole('textbox', { name: 'Document content', exact: true }).fill('Shared parenting responsibilities.')
  await modal.getByRole('button', { name: 'Create Document', exact: true }).click()
  await expect(page.getByRole('dialog').getByText('Shared parenting responsibilities.', { exact: true })).toBeVisible()
  expect(new URL(page.url()).searchParams.get('crewId')).toBe(crewId)
  await page.getByRole('dialog').getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByRole('textbox', { name: 'Document content', exact: true }).fill('Updated responsibilities and weekly check-ins.')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByText('Document saved.', { exact: true })).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).last().click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('link', { name: 'Back to Agreement Crew documents', exact: true }).click()
  await expect(page).toHaveURL(/\/app\/crews\/detail\?id=.*&tab=documents$/)
  await page.getByRole('button', { name: 'Open Our agreement', exact: true }).click()
  await expect(page.getByText('Updated responsibilities and weekly check-ins.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Sign document', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Sign document', exact: true })).toHaveCount(0)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('Our agreement.txt')
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).last().click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('link', { name: 'Create Document', exact: true }).click()
  await expect(page).toHaveURL(/\/app\/legal\?crewId=/)
  await page.getByRole('button', { name: 'Open Our agreement', exact: true }).click()
  await expect(page.getByText('Updated responsibilities and weekly check-ins.', { exact: true })).toBeVisible()
  await expect(page.getByRole('dialog').getByText('signed', { exact: true })).toBeVisible()
})
